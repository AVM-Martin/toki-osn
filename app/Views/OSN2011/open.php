    <h3>
        <a href="https://toki.id/2011/olimpiade-sains-nasional-informatika-terbuka-2011/" target="blank">Olimpiade Sains Nasional Informatika Terbuka 2011</a>
    </h3>

    <img src="/images/openosn2015.png" width="250">

    <p><strong>Olimpiade Sains Nasional Informatika Terbuka 2011</strong> (untuk selanjutnya disebut OSN Terbuka) adalah olimpiade yang berbentuk kompetisi pemrograman yang diadakan bersamaan dengan OSN 2011 bidang informatika yang diadakan di Manado, Sulawesi Utara.</p>
    <p>Tujuan diadakannya OSN Terbuka ini adalah untuk memberikan kesempatan kepada peserta yang karena satu dan lain hal tidak diundang ke OSN 2011 di Manado. OSN Terbuka dilaksanakan dengan menggunakan <strong>prosedur dan aturan yang serupa </strong>dengan OSN Informatika 2011.</p>
    <p>OSN Terbuka diadakan tanggal <strong>12 s.d. 14 September 2011</strong> secara <strong>onsite </strong>dan <strong>online</strong>. Kompetisi onsite dapat diikuti di beberapa perguruan tinggi yang sudah bekerja sama dengan panitia OSN Terbuka, sedangkan kompetisi online dapat diikuti dari tempat masing-masing peserta. OSN Terbuka dapat diikuti oleh siapa pun yang memenuhi syarat sebagai peserta.</p>
    <p>Setiap calon peserta <strong>wajib mengunduh dan membaca memahami dokumen Pedoman OSN Informatika Terbuka 2011 terlampir</strong>. Pastikan Anda memahami poin-poin berikut:</p>

    <ol>
        <li>Soal, pembobotan nilai, dan jadwal OSN Terbuka menyerupai OSN Informatika 2011 di Manado</li>
        <li>Terdapat dua macam peserta, <strong>online atau onsite</strong></li>
        <li>Terdapat <strong>enam site OSN Terbuka onsite</strong>: UI, ITB, UGM, ITS, IPB, dan UNAND.</li>
        <li>Prosedur <strong>pendaftaran dilakukan di www.tokilearning.org</strong> pada <strong>menu ‘Kontes’ OSN Informatika Terbuka 2011</strong> dan <strong>jangan lupa untuk memilih site yang Anda inginkan di menu <a href="#">‘Sunting Profil’</a></strong> (pendaftaran baru dianggap valid jika kolom ‘Site’ tidak kosong). Lengkapi juga bagian <strong>Informasi Umum</strong> untuk mempermudah administrasi lomba.</li>
    </ol>

    <p>Pertanyaan mengenai OSN Terbuka dapat ditanyakan melalui email ke <em>open.osn@gmail.com</em>.</p>
